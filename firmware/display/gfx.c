/* 1-bpp drawing on the MIP framebuffer; font and digits drawn for this project. */
#include "gfx.h"

static void put(struct mip *m, int x, int y, int ink)
{
    uint8_t *b;
    uint8_t bit;
    if ((unsigned)x >= MIP_W || (unsigned)y >= MIP_H)
        return;
    b = &m->fb[y][x >> 3];
    bit = (uint8_t)(0x80 >> (x & 7));
    if (ink)
        *b |= bit;
    else
        *b &= (uint8_t)~bit;
}

void gfx_pixel(struct mip *m, int x, int y, int ink)
{
    put(m, x, y, ink);
    mip_mark_dirty(m, y, y);
}

void gfx_clear(struct mip *m, int ink)
{
    int y, x;
    for (y = 0; y < MIP_H; y++)
        for (x = 0; x < MIP_STRIDE; x++)
            m->fb[y][x] = ink ? 0xff : 0x00;
    mip_mark_all(m);
}

void gfx_fill_rect(struct mip *m, int x, int y, int w, int h, int ink)
{
    int i, j;
    if (w <= 0 || h <= 0)
        return;
    for (j = y; j < y + h; j++)
        for (i = x; i < x + w; i++)
            put(m, i, j, ink);
    mip_mark_dirty(m, y, y + h - 1);
}

void gfx_hline(struct mip *m, int x, int y, int w, int ink)
{
    gfx_fill_rect(m, x, y, w, 1, ink);
}

void gfx_rect(struct mip *m, int x, int y, int w, int h, int ink)
{
    gfx_fill_rect(m, x, y, w, 1, ink);
    gfx_fill_rect(m, x, y + h - 1, w, 1, ink);
    gfx_fill_rect(m, x, y, 1, h, ink);
    gfx_fill_rect(m, x + w - 1, y, 1, h, ink);
}

