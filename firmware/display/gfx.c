static const uint8_t *glyph(char c)
{
    static const uint8_t blank[7] = {0};
    unsigned i;
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    if (c >= '0' && c <= '9')
        return font_digits[c - '0'];
    if (c >= 'A' && c <= 'Z')
        return font_alpha[c - 'A'];
    for (i = 0; i < sizeof(font_punct) / sizeof(font_punct[0]); i++)
        if (font_punct[i].c == c)
            return font_punct[i].rows;
    return blank;
}

int gfx_text_width(const char *s, int scale)
{
    int n = 0;
    while (s[n])
        n++;
    return n ? n * 6 * scale - scale : 0;
}

int gfx_text(struct mip *m, int x, int y, const char *s, int scale, int ink)
{
    for (; *s; s++) {
        const uint8_t *g = glyph(*s);
        int r, c;
        for (r = 0; r < 7; r++)
            for (c = 0; c < 5; c++)
                if (g[r] & (0x10 >> c))
                    gfx_fill_rect(m, x + c * scale, y + r * scale, scale, scale, ink);
        x += 6 * scale;
    }
    mip_mark_dirty(m, y, y + 7 * scale - 1);
    return x;
}

/* Segment masks: bit0 a (top), 1 b (upper right), 2 c (lower right),
 * 3 d (bottom), 4 e (lower left), 5 f (upper left), 6 g (middle). */
static const uint8_t seg_mask[10] = {0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F};

void gfx_seg_digit(struct mip *m, int x, int y, int w, int h, int t, int digit)
{
    uint8_t s;
    int mid = y + (h - t) / 2, g = 1; /* 1 px gap between segments */
    if (digit < 0 || digit > 9)
        return;
    s = seg_mask[digit];
    if (s & 0x01) gfx_fill_rect(m, x + t + g, y, w - 2 * (t + g), t, 1);
    if (s & 0x40) gfx_fill_rect(m, x + t + g, mid, w - 2 * (t + g), t, 1);
    if (s & 0x08) gfx_fill_rect(m, x + t + g, y + h - t, w - 2 * (t + g), t, 1);
    if (s & 0x20) gfx_fill_rect(m, x, y + t / 2 + g, t, mid - y - g * 2, 1);
    if (s & 0x02) gfx_fill_rect(m, x + w - t, y + t / 2 + g, t, mid - y - g * 2, 1);
    if (s & 0x10) gfx_fill_rect(m, x, mid + t / 2 + g, t, y + h - t / 2 - mid - t / 2 - 2 * g, 1);
    if (s & 0x04) gfx_fill_rect(m, x + w - t, mid + t / 2 + g, t, y + h - t / 2 - mid - t / 2 - 2 * g, 1);
    mip_mark_dirty(m, y, y + h - 1);
}

void gfx_icon16(struct mip *m, int x, int y, const uint16_t *rows, int nrows, int scale)
{
    int r, c;
    for (r = 0; r < nrows; r++)
        for (c = 0; c < 16; c++)
            if (rows[r] & (0x8000u >> c))
                gfx_fill_rect(m, x + c * scale, y + r * scale, scale, scale, 1);
    mip_mark_dirty(m, y, y + nrows * scale - 1);
}
