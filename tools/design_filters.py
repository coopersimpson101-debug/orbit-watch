#!/usr/bin/env python3
"""Design the PPG band-pass used by firmware/app/hr.c and emit a C header.

Two second-order Butterworth sections (high-pass 0.5 Hz, low-pass 4 Hz) at
the PPG sample rate, via the bilinear transform with frequency pre-warping.
Written out by hand (no scipy) so the maths is visible:

  analogue prototype   H(s) = w^2 / (s^2 + sqrt(2) w s + w^2)          (low-pass)
                       H(s) = s^2 / (s^2 + sqrt(2) w s + w^2)          (high-pass)
  pre-warp             w = 2 fs tan(pi fc / fs)
  bilinear             s = 2 fs (1 - z^-1) / (1 + z^-1)

Coefficients are stored as Q28 integers (b0 b1 b2 a1 a2, a0 normalised to 1).

    python tools/design_filters.py            # rewrite firmware/include/hr_coeffs.h
    python tools/design_filters.py --check    # exit 1 if the header is stale
"""
from __future__ import annotations

import argparse
import cmath
import math
import sys
from pathlib import Path

FS = 25.0
HP_FC = 0.5
LP_FC = 4.0
Q = 28
OUT = Path(__file__).resolve().parent.parent / "firmware" / "include" / "hr_coeffs.h"


def butter2(fc: float, fs: float, kind: str) -> tuple[list[float], list[float]]:
    k = 2.0 * fs
    w = k * math.tan(math.pi * fc / fs)   # pre-warped analogue cut-off
    r2 = math.sqrt(2.0)
    # denominator s^2 + r2 w s + w^2 with s = k (1 - z^-1)/(1 + z^-1), times (1 + z^-1)^2
    a0 = k * k + r2 * w * k + w * w
    a1 = 2.0 * (w * w - k * k)
    a2 = k * k - r2 * w * k + w * w
    if kind == "lp":
        b = [w * w, 2.0 * w * w, w * w]
    else:
        b = [k * k, -2.0 * k * k, k * k]
    return [x / a0 for x in b], [1.0, a1 / a0, a2 / a0]


def response(b, a, f, fs=FS) -> float:
    z = cmath.exp(-2j * math.pi * f / fs)
    num = b[0] + b[1] * z + b[2] * z * z
    den = a[0] + a[1] * z + a[2] * z * z
    return abs(num / den)


def q(x: float) -> int:
    return int(round(x * (1 << Q)))


def header() -> str:
    hp = butter2(HP_FC, FS, "hp")
    lp = butter2(LP_FC, FS, "lp")
    lines = [
        "/* Generated by tools/design_filters.py - do not edit. */",
        "#ifndef OW_HR_COEFFS_H", "#define OW_HR_COEFFS_H", "",
        f"#define HR_COEF_Q {Q}",
        f"/* fs = {FS:g} Hz; 2nd-order Butterworth sections via the bilinear transform */",
    ]
    for name, (b, a), fc in (("HP", hp, HP_FC), ("LP", lp, LP_FC)):
        lines.append(f"/* {name} fc = {fc:g} Hz: b = {b[0]:.9f} {b[1]:.9f} {b[2]:.9f}, "
                     f"a = 1 {a[1]:.9f} {a[2]:.9f} */")
        lines.append(f"#define HR_{name}_B0 ({q(b[0])})")
        lines.append(f"#define HR_{name}_B1 ({q(b[1])})")
        lines.append(f"#define HR_{name}_B2 ({q(b[2])})")
        lines.append(f"#define HR_{name}_A1 ({q(a[1])})")
        lines.append(f"#define HR_{name}_A2 ({q(a[2])})")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = header()
    if args.check:
        return 0 if OUT.read_text() == text else 1
    OUT.write_text(text, newline="\n")
    hp = butter2(HP_FC, FS, "hp")
    lp = butter2(LP_FC, FS, "lp")
    for f in (0.1, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 10.0):
        g = response(*hp, f) * response(*lp, f)
        print(f"{f:5.2f} Hz  |H| = {g:.4f}  ({20 * math.log10(g):6.1f} dB)")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
